#!/usr/bin/env node
// Regenerate the registry (src/fx/index.js) and the catalog (docs/CATALOG.md) from the effect files.
//
//   node tools/index.mjs

import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, FX_DIR, VARIANT, allIds, loadEffect } from "./lib/fxlib.mjs";
import { categories } from "../src/fx/categories.js";

// one entry per effect file; has3d when it also exports a 3D variant
const metas = [];
const all = new Set(allIds());
for (const id of allIds(FX_DIR, { variants: false })) {
  try {
    metas.push({ id, has3d: all.has(id + VARIANT), ...(await loadEffect(id)).meta });
  } catch (e) {
    console.error(`skipping ${id}: ${String(e.message ?? e).split("\n")[0]}`);
  }
}
const order = new Map(categories.map((c, i) => [c.id, i]));
const rank = (id) => order.get(id.split("/")[0]) ?? 99;
metas.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
const ids = metas.map((m) => m.id);
// what can be seen in 3D: native 3D effects and every 2D effect with a variant
const in3dCount = metas.filter((m) => m.camera || m.has3d).length;

const ident = (id) => "fx_" + id.replace(/[^a-z0-9]+/gi, "_");
const lines = [
  "// Generated by tools/index.mjs: every effect, by id. Don't edit; run `node tools/index.mjs`.",
  "// An effect with a 3D variant is listed again as <id>@3d.",
  "",
  `import { in3d } from "../core/fx.js";`,
  ...ids.map((id) => `import * as ${ident(id)} from "./${id}.js";`),
  "",
  `export { categories } from "./categories.js";`,
  "",
  "export const effects = {",
  ...metas.flatMap((m) => [`  "${m.id}": ${ident(m.id)},`, ...(m.has3d ? [`  "${m.id}${VARIANT}": in3d(${ident(m.id)}),`] : [])]),
  "};",
  "",
];
writeFileSync(join(FX_DIR, "index.js"), lines.join("\n"));

const md = [
  "# Catalog",
  "",
  `${ids.length} effects in ${categories.filter((c) => metas.some((m) => m.id.startsWith(c.id + "/"))).length} categories, ${in3dCount} of them in 3D. Every one is a file in`,
  "`src/fx/<category>/<name>.js`; render any of them with `node tools/render.mjs <id> --gif`, and a 3D variant with",
  "`node tools/render.mjs <id>@3d`.",
  "",
];
for (const c of categories) {
  const list = metas.filter((m) => m.id.startsWith(c.id + "/"));
  if (!list.length) continue;
  md.push(`## ${c.name}`, "", `${c.blurb}.`, "", "| effect | id | | size | 3d | what it does |", "|---|---|---|---|---|---|");
  for (const m of list)
    md.push(`| ${m.name} | \`${m.id}\` | ${m.loop ? "loop" : "one-shot"} ${+m.duration.toFixed(2)}s | ${m.size[0]}×${m.size[1]} | ${m.camera ? "3D only" : m.has3d ? `\`@3d\`` : ""} | ${m.desc.replace(/\|/g, "\\|")} |`);
  md.push("");
}
writeFileSync(join(ROOT, "docs", "CATALOG.md"), md.join("\n"));
console.log(`${ids.length} effects (${in3dCount} in 3D) -> src/fx/index.js, docs/CATALOG.md`);

// README: the counts and the category table
const readme = join(ROOT, "README.md");
const rows = categories
  .map((c) => [c, metas.filter((m) => m.id.startsWith(c.id + "/"))])
  .filter(([, list]) => list.length)
  .map(([c, list]) => `| **${c.name}** | ${list.length} | ${list.filter((m) => m.camera || m.has3d).length} | ${list.slice(0, 6).map((m) => m.name.toLowerCase()).join(", ")}${list.length > 6 ? "…" : ""} |`);
const table = ["| category | effects | in 3D | some of them |", "|---|---|---|---|", ...rows].join("\n");
let text = readFileSync(readme, "utf8");
text = text.replace(/<!-- count -->[\s\S]*?<!-- \/count -->/, `<!-- count -->${ids.length}<!-- /count -->`);
text = text.replace(/<!-- count3d -->[\s\S]*?<!-- \/count3d -->/, `<!-- count3d -->${in3dCount}<!-- /count3d -->`);
text = text.replace(/<!-- catalog -->[\s\S]*?<!-- \/catalog -->/, `<!-- catalog -->\n${table}\n<!-- /catalog -->`);
writeFileSync(readme, text);
